CREATE VIEW public.visao_geral_estoque AS
 SELECT p.id AS peca_id,
    p.codigo,
    p.nome,
    c.nome AS categoria,
    s.nome AS fornecedor,
    p.quantidade_estoque,
    p.estoque_minimo,
    p.preco_unitario,
    (((p.quantidade_estoque)::numeric * p.preco_unitario))::numeric(14,2) AS valor_estoque,
    p.localizacao_deposito,
    p.ativo,
        CASE
            WHEN (NOT p.ativo) THEN 'Inativo'::text
            WHEN (p.quantidade_estoque = 0) THEN 'Sem estoque'::text
            WHEN (p.quantidade_estoque <= p.estoque_minimo) THEN 'Estoque baixo'::text
            ELSE 'Disponivel'::text
        END AS situacao_estoque,
    p.criado_em_utc,
    p.atualizado_em_utc
   FROM ((public.pecas p
     JOIN public.categorias c ON ((c.id = p.categoria_id)))
     LEFT JOIN public.fornecedores s ON ((s.id = p.fornecedor_id)));


